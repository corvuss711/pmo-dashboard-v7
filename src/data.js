export function regionSlice(def, key, region) {
  const idx = REGIONS.indexOf(region);
  const w = REGION_W[key];
  if (idx < 0 || !w) return { num: def.num, den: def.den };
  const dens = w.map((x, i) => (i === w.length - 1 ? null : Math.round(def.den * x[0])));
  dens[dens.length - 1] = def.den - dens.slice(0, -1).reduce((a, b) => a + b, 0);
  const raw = w.map((x, i) => Math.max(0, dens[i]) * x[1]);
  const tot = raw.reduce((a, b) => a + b, 0);
  const scale = tot > 0 ? def.num / tot : 0;
  const nums = raw.map((r, i) => Math.min(Math.max(0, dens[i]), Math.round(r * scale)));
  return { num: nums[idx], den: Math.max(0, dens[idx]) };
}

