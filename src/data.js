export function rangeFactor(from, to) {
  const days = Math.max(1, Math.round((new Date(to) - new Date(from)) / 86400000) + 1);
  return { days, factor: Math.min(1, 0.42 + 0.58 * (days / 192)) };
}

export function metricView(def, id, key, region, rf) {
  const sl = region && region !== "All-Delhi NCR" ? regionSlice(def, key, region) : { num: def.num, den: def.den };
  const num = Math.round(sl.num * rf);
  const den = sl.den;
  const has = den > 0;
  if (def.rate) {
    const v = has ? Math.round(num / den) : 0;
    return { ...def, id, raw: 100,
      pct: has ? nf(v) + (def.unit || "") : "\u2014",
      frac: has ? nf(num) + " / " + nf(den) : "no data",
      fracLong: has ? nf(num) + " " + def.numL + " across " + nf(den) + " " + def.denL : "no data in range",
      bar: "0%", flag: "#5A5C5E", track: "#EDEDE8", status: has ? "Rate \u2014 no target band" : "No data" };
  }
  const p = has ? Math.round((num / den) * 100) : 0;
  const band = def.invert ? 100 - p : p;
  return { ...def, id, raw: band, den,
    pct: has ? p + "%" : "\u2014",
    frac: has ? nf(num) + " / " + nf(den) : "no data",
    fracLong: has ? nf(num) + " " + def.numL + " of " + nf(den) + " " + def.denL : "no data in range",
    bar: (has ? Math.min(100, p) : 0) + "%",
    flag: has ? flag(band) : "#C4C4BE",
    track: has ? track(band) : "#EDEDE8",
    status: has ? statusWord(band) : "No data" };
}

/* A segment either selects rows tagged with it, or rescales untagged rows by its
   share of the base (mult) and its relative performance (perf). */
export function segApply(defs, ini, segKey) {
  if (!ini.splits) return defs;
  const cur = ini.splits.find((v) => v.key === segKey) || ini.splits[0];
  const tagged = defs.some((x) => x.seg);
  return defs.filter((x) => !x.seg || x.seg === cur.key).map((x) => {
    if (x.seg || tagged) return x;
    const den = Math.round(x.den * cur.mult);
    return { ...x, den, num: Math.min(den, Math.round(x.num * cur.mult * (cur.perf || 1))) };
  });
}

// raw = every segment together, used by the tile levels
export const l1Of = (ini, region, rf, seg, raw) =>
  (raw ? ini.l1 : segApply(ini.l1, ini, seg)).map((d, i) => metricView(d, "L1-" + i, ini.key, region, rf));
export const l2Of = (ini, region, rf, seg, raw) =>
  (raw ? ini.metrics : segApply(ini.metrics, ini, seg)).map((d, i) => metricView(d, "L2-" + i, ini.key, region, rf));

